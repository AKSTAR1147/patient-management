package ink.starblog.patientservice.kafka;

import ink.starblog.patientservice.model.Patient;
import lombok.extern.log4j.Log4j;
import lombok.extern.slf4j.Slf4j;
import org.springframework.kafka.core.KafkaTemplate;
import org.springframework.stereotype.Service;
import patient.events.PatientEvent;

@Slf4j
@Service
public class KafkaProducer  {
    private final KafkaTemplate<String, byte[]> kafkaTemplate;

    KafkaProducer(KafkaTemplate<String, byte[]> kafkaTemplate){
        this.kafkaTemplate=kafkaTemplate;
    }

    //sending of actual event
    public void sendEvent(Patient patient){
        //below the PatientEvent calss is generated by proto
        PatientEvent event  = PatientEvent.newBuilder()
                .setPatientId(patient.getId().toString())
                .setName(patient.getName())
                .setEmail(patient.getEmail())
                .setEventType("PATIENT_CREATED")
                .build();
        //event creation completed
        try{
            kafkaTemplate.send("patient",event.toByteArray());
        }catch(Exception e){
            log.error("Error sending PatientCreatedn event {}",event);
        }
        //event sending completed
    }
}
